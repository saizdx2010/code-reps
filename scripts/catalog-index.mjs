// Builds src/catalog-index.ts: the small synchronous catalog the app renders from at startup.
// The heavy rep and lesson payloads load on demand; tests/catalog-index.test.mjs fails when this file is stale.
// Run directly (`yarn content:index`) to write the file; tests import renderCatalogIndex without writing.
import { writeFile } from 'node:fs/promises'
import { readFileSync, realpathSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { repSources } from '../src/rep-sources.ts'
import { skills } from '../src/knowledge.ts'
import { starterHash } from '../src/starter-hash.ts'
import initSqlJs from 'sql.js'

const words = text => text.split(/\s+/).filter(Boolean).length
/** Words in the brief the learner reads: the structured brief when there is one, otherwise the prompt. */
const briefWords = rep =>
  rep.brief
    ? words(rep.brief.summary) +
      rep.brief.rules.reduce((sum, rule) => sum + words(rule), 0) +
      (rep.brief.edgeCases ?? []).reduce((sum, item) => sum + words(item), 0)
    : words(rep.prompt)

const line = value => `  ${JSON.stringify(value)},`

/** The app's lazy loader for each source, read from the static imports and entries of src/rep-sources.ts so that list stays the only one. */
function sourceLoaders() {
  const text = readFileSync(new URL('../src/rep-sources.ts', import.meta.url), 'utf8')
  const modules = new Map()
  for (const [, names, path] of text.matchAll(/^import \{ ([^}]+) \} from '(\.\/[^']+)'$/gm))
    for (const name of names.split(', ')) modules.set(name, path)
  const entries = [...text.matchAll(/^  \{ name: '([^']+)', reps: (\w+)(?:, lessons: (\w+))? \},$/gm)]
  if (entries.map(entry => entry[1]).join() !== repSources.map(source => source.name).join())
    throw new Error('Could not read every entry of src/rep-sources.ts; keep each on one line as { name, reps, lessons? }')
  return entries.map(([, name, reps, lessons]) => {
    const path = modules.get(reps)
    if (!path || (lessons && modules.get(lessons) !== path))
      throw new Error(`Import the reps and lessons of ${name} from one module in src/rep-sources.ts`)
    return `  '${name}': source(() => import('${path}'), module => ({ reps: module.${reps}${lessons ? `, lessons: module.${lessons}` : ''} })),`
  })
}

/** src/rep-chunks.ts: kept out of the catalog so only src/rep-content.ts, not every startup chunk, holds the dynamic imports. */
export function renderRepChunks() {
  return `// Generated by scripts/catalog-index.mjs from src/rep-sources.ts. Do not edit by hand: run \`yarn content:index\` after changing a rep source.
// Lazy loaders for the heavy content of each rep source. Each module becomes its own chunk. Only src/rep-content.ts imports this file.
import type { RepSourceName } from './catalog-index.ts'
import { source, type RepSourceLoader } from './rep-source-loader.ts'

export const repSourceLoaders: Record<RepSourceName, RepSourceLoader> = {
${sourceLoaders().join('\n')}
}
`
}

export function renderCatalogIndex() {
  const repEntries = []
  const seen = new Set()
  for (const source of repSources) {
    for (const rep of source.reps) {
      if (seen.has(rep.id)) throw new Error(`Duplicate rep id ${rep.id}`)
      seen.add(rep.id)
      repEntries.push({
        id: rep.id,
        title: rep.title,
        category: rep.category,
        ...(rep.format ? { format: rep.format } : {}),
        starterHash: starterHash(rep.starter),
        hintTotal: rep.hints.length,
        briefWords: briefWords(rep),
        checkTotal: rep.checks.length,
        source: source.name,
      })
    }
  }
  const foundationRepIds = []
  for (const source of repSources) {
    for (const lesson of source.lessons ?? []) {
      if (!source.reps.some(rep => rep.id === lesson.repId))
        throw new Error(`Lesson for ${lesson.repId} must live in the same source as its rep (${source.name})`)
      if (source.name === 'foundations') foundationRepIds.push(lesson.repId)
    }
  }
  const skillEntries = skills.map(skill => ({
    id: skill.id,
    title: skill.title,
    summary: skill.summary,
    prerequisites: skill.prerequisites,
    related: skill.related,
    repIds: skill.repIds,
    firstMistake: skill.mistakes[0] ?? '',
    questions: skill.questions.map(question => ({
      id: question.id,
      optionCount: question.options.length,
      answer: question.answer,
      ...(question.completion ? { completion: true, answerText: question.options[question.answer] } : {}),
    })),
  }))
  const names = repSources.map(source => `'${source.name}'`).join(' | ')
  // Rows instead of objects: every rep repeats the same keys, category, and source, and the index loads at startup.
  const categories = [...new Set(repEntries.map(entry => entry.category))]
  const sourceNames = repSources.map(source => source.name)
  const repRows = repEntries.map(entry => [
    entry.id,
    entry.title,
    categories.indexOf(entry.category),
    entry.format ?? 0,
    entry.starterHash,
    entry.hintTotal,
    entry.briefWords,
    entry.checkTotal,
    sourceNames.indexOf(entry.source),
  ])
  return `// Generated by scripts/catalog-index.mjs. Do not edit by hand: run \`yarn content:index\` after changing a rep or lesson.
// This is the small catalog the app renders from at startup. Heavy rep and lesson content loads on demand.
import type { Rep } from './rep-types.ts'

export type RepSourceName = ${names}
export type RepSummary = { id: string; title: string; category: string; format?: Rep['format']; starterHash: string; hintTotal: number; briefWords: number; checkTotal: number; source: RepSourceName }
export type QuestionSummary = { id: string; optionCount: number; answer: number; completion?: true; answerText?: string }
export type SkillSummary = { id: string; title: string; summary: string; prerequisites: string[]; related: string[]; repIds: string[]; firstMistake: string; questions: QuestionSummary[] }

const sources: RepSourceName[] = ${JSON.stringify(sourceNames)}
const categories: string[] = ${JSON.stringify(categories)}
// [id, title, category, format or 0, starterHash, hintTotal, briefWords, checkTotal, source]
const repRows: [string, string, number, Rep['format'] | 0, string, number, number, number, number][] = [
${repRows.map(line).join('\n')}
]

export const repIndex: RepSummary[] = repRows.map(([id, title, category, format, starterHash, hintTotal, briefWords, checkTotal, source]) => ({
  id,
  title,
  category: categories[category],
  ...(format ? { format } : {}),
  starterHash,
  hintTotal,
  briefWords,
  checkTotal,
  source: sources[source],
}))

/** Foundations reps, in lesson order. Each has a short lesson before it. */
export const foundationRepIds: string[] = ${JSON.stringify(foundationRepIds)}

export const skillIndex: SkillSummary[] = [
${skillEntries.map(line).join('\n')}
]
`
}

/** Splits a CREATE TABLE body at its top-level commas, keeping commas inside parentheses and quotes. */
function columnDefinitions(createSql) {
  const body = createSql.slice(createSql.indexOf('(') + 1, createSql.lastIndexOf(')'))
  const parts = []
  let depth = 0
  let quote = ''
  let current = ''
  for (const character of body) {
    if (quote) {
      if (character === quote) quote = ''
    } else if (character === "'" || character === '"') quote = character
    else if (character === '(') depth++
    else if (character === ')') depth--
    else if (character === ',' && depth === 0) {
      parts.push(current)
      current = ''
      continue
    }
    current += character
  }
  parts.push(current)
  return parts
    .map(part => part.replace(/\s+/g, ' ').trim())
    .filter(Boolean)
    .map(part => part.replace(/\bREFERENCES\s+("?)(\w+)\1\s*\(\s*(\w+)\s*\)/gi, '→ $2.$3'))
}

/**
 * src/sql-previews.ts: what a SQLite rep's brief shows of its starting data, produced by running the rep's own schema and
 * first seed through SQLite, the same source the checks load. The brief loads it with the rep, never at startup.
 */
export async function renderSqlPreviews() {
  const SQL = await initSqlJs()
  const previews = {}
  for (const source of repSources)
    for (const rep of source.reps) {
      if (!rep.sql) continue
      const [seedName, seed] = Object.entries(rep.sql.seeds)[0]
      const db = new SQL.Database()
      try {
        db.run(`${rep.sql.schema}\n${seed.sql}`)
        const read = sql => db.exec(sql)[0] ?? { columns: [], values: [] }
        const tables = read(
          "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid",
        ).values.map(([name, createSql]) => {
          const quoted = `"${String(name).replaceAll('"', '""')}"`
          const sample = read(`SELECT * FROM ${quoted} LIMIT 3`)
          const columns = db.prepare(`SELECT * FROM ${quoted}`)
          const names = columns.getColumnNames()
          columns.free()
          return {
            name,
            rows: read(`SELECT COUNT(*) FROM ${quoted}`).values[0][0],
            definition: columnDefinitions(createSql),
            columns: names,
            sample: sample.values,
          }
        })
        const check = rep.sql.compare === 'state' ? undefined : rep.checks.find(item => item.sql?.seed === seedName)
        previews[rep.id] = {
          seed: seedName,
          tables,
          ...(check ? { example: { columns: rep.sql.columns ?? [], rows: check.expected.rows } } : {}),
        }
      } finally {
        db.close()
      }
    }
  return `// Generated by scripts/catalog-index.mjs from each SQLite rep's schema and first seed. Do not edit by hand: run
// \`yarn content:index\` after changing a SQLite rep. The brief loads this with the rep; it is never part of startup.
import type { SqlValue } from './rep-types.ts'

export type SqlTablePreview = { name: string; rows: number; definition: string[]; columns: string[]; sample: SqlValue[][] }
export type SqlPreview = { seed: string; tables: SqlTablePreview[]; example?: { columns: string[]; rows: SqlValue[][] } }

export const sqlPreviews: Record<string, SqlPreview> = {
${Object.entries(previews)
  .map(([id, preview]) => `  ${JSON.stringify(id)}: ${JSON.stringify(preview)},`)
  .join('\n')}
}
`
}

function isEntryPoint() {
  try {
    return Boolean(process.argv[1]) && realpathSync(resolve(process.argv[1])) === fileURLToPath(import.meta.url)
  } catch {
    return false
  }
}

if (isEntryPoint()) {
  await writeFile(new URL('../src/catalog-index.ts', import.meta.url), renderCatalogIndex())
  await writeFile(new URL('../src/rep-chunks.ts', import.meta.url), renderRepChunks())
  await writeFile(new URL('../src/sql-previews.ts', import.meta.url), await renderSqlPreviews())
  console.log('Wrote src/catalog-index.ts, src/rep-chunks.ts, and src/sql-previews.ts')
}
