// Builds src/catalog-index.ts: the small synchronous catalog the app renders from at startup.
// The heavy rep and lesson payloads load on demand; tests/catalog-index.test.mjs fails when this file is stale.
// Run directly (`yarn content:index`) to write the file; tests import renderCatalogIndex without writing.
import { writeFile } from 'node:fs/promises'
import { readFileSync, realpathSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { repSources } from '../src/rep-sources.ts'
import { skills } from '../src/knowledge.ts'
import { starterHash } from '../src/starter-hash.ts'

const words = text => text.split(/\s+/).filter(Boolean).length
/** Words in the brief the learner reads: the structured brief when there is one, otherwise the prompt. */
const briefWords = rep => rep.brief ? words(rep.brief.summary) + rep.brief.rules.reduce((sum, rule) => sum + words(rule), 0) + (rep.brief.edgeCases ?? []).reduce((sum, item) => sum + words(item), 0) : words(rep.prompt)

const line = value => `  ${JSON.stringify(value)},`

/** The app's lazy loader for each source, read from the static imports and entries of src/rep-sources.ts so that list stays the only one. */
function sourceLoaders() {
  const text = readFileSync(new URL('../src/rep-sources.ts', import.meta.url), 'utf8')
  const modules = new Map()
  for (const [, names, path] of text.matchAll(/^import \{ ([^}]+) \} from '(\.\/[^']+)'$/gm)) for (const name of names.split(', ')) modules.set(name, path)
  const entries = [...text.matchAll(/^  \{ name: '([^']+)', reps: (\w+)(?:, lessons: (\w+))? \},$/gm)]
  if (entries.map(entry => entry[1]).join() !== repSources.map(source => source.name).join()) throw new Error('Could not read every entry of src/rep-sources.ts; keep each on one line as { name, reps, lessons? }')
  return entries.map(([, name, reps, lessons]) => {
    const path = modules.get(reps)
    if (!path || (lessons && modules.get(lessons) !== path)) throw new Error(`Import the reps and lessons of ${name} from one module in src/rep-sources.ts`)
    return `  '${name}': source(() => import('${path}'), module => ({ reps: module.${reps}${lessons ? `, lessons: module.${lessons}` : ''} })),`
  })
}

/** src/rep-chunks.ts: kept out of the catalog so only src/rep-content.ts, not every startup chunk, holds the dynamic imports. */
export function renderRepChunks() {
  return `// Generated by scripts/catalog-index.mjs from src/rep-sources.ts. Do not edit by hand: run \`yarn content:index\` after changing a rep source.
// Lazy loaders for the heavy content of each rep source. Each module becomes its own chunk. Only src/rep-content.ts imports this file.
import type { RepSourceName } from './catalog-index.ts'
import { source, type RepSourceLoader } from './rep-source-loader.ts'

export const repSourceLoaders: Record<RepSourceName, RepSourceLoader> = {
${sourceLoaders().join('\n')}
}
`
}

export function renderCatalogIndex() {
  const repEntries = []
  const seen = new Set()
  for (const source of repSources) {
    for (const rep of source.reps) {
      if (seen.has(rep.id)) throw new Error(`Duplicate rep id ${rep.id}`)
      seen.add(rep.id)
      repEntries.push({ id: rep.id, title: rep.title, category: rep.category, ...(rep.format ? { format: rep.format } : {}), starterHash: starterHash(rep.starter), hintTotal: rep.hints.length, briefWords: briefWords(rep), checkTotal: rep.checks.length, source: source.name })
    }
  }
  const foundationRepIds = []
  for (const source of repSources) {
    for (const lesson of source.lessons ?? []) {
      if (!source.reps.some(rep => rep.id === lesson.repId)) throw new Error(`Lesson for ${lesson.repId} must live in the same source as its rep (${source.name})`)
      if (source.name === 'foundations') foundationRepIds.push(lesson.repId)
    }
  }
  const skillEntries = skills.map(skill => ({
    id: skill.id, title: skill.title, summary: skill.summary, prerequisites: skill.prerequisites, related: skill.related, repIds: skill.repIds,
    firstMistake: skill.mistakes[0] ?? '',
    questions: skill.questions.map(question => ({
      id: question.id, optionCount: question.options.length, answer: question.answer,
      ...(question.completion ? { completion: true, answerText: question.options[question.answer] } : {}),
    })),
  }))
  const names = repSources.map(source => `'${source.name}'`).join(' | ')
  return `// Generated by scripts/catalog-index.mjs. Do not edit by hand: run \`yarn content:index\` after changing a rep or lesson.
// This is the small catalog the app renders from at startup. Heavy rep and lesson content loads on demand.
import type { Rep } from './rep-types.ts'

export type RepSourceName = ${names}
export type RepSummary = { id: string; title: string; category: string; format?: Rep['format']; starterHash: string; hintTotal: number; briefWords: number; checkTotal: number; source: RepSourceName }
export type QuestionSummary = { id: string; optionCount: number; answer: number; completion?: true; answerText?: string }
export type SkillSummary = { id: string; title: string; summary: string; prerequisites: string[]; related: string[]; repIds: string[]; firstMistake: string; questions: QuestionSummary[] }

export const repIndex: RepSummary[] = [
${repEntries.map(line).join('\n')}
]

/** Foundations reps, in lesson order. Each has a short lesson before it. */
export const foundationRepIds: string[] = ${JSON.stringify(foundationRepIds)}

export const skillIndex: SkillSummary[] = [
${skillEntries.map(line).join('\n')}
]
`
}

function isEntryPoint() {
  try { return Boolean(process.argv[1]) && realpathSync(resolve(process.argv[1])) === fileURLToPath(import.meta.url) }
  catch { return false }
}

if (isEntryPoint()) {
  await writeFile(new URL('../src/catalog-index.ts', import.meta.url), renderCatalogIndex())
  await writeFile(new URL('../src/rep-chunks.ts', import.meta.url), renderRepChunks())
  console.log('Wrote src/catalog-index.ts and src/rep-chunks.ts')
}
