// Builds src/icon-pack.css from src/icon-pack.ts: one @keyframes and one --icon-react-<name> per reaction,
// and the mask images for the icons that CSS draws itself (disclosure markers, checkbox ticks).
// Run directly (`yarn icons`) to write the file; tests/icon-pack.test.mjs fails when it is stale.
import { writeFile } from 'node:fs/promises'
import { realpathSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { REACTIONS, iconSvg } from '../src/icon-pack.ts'

/** Icons that stylesheets use as mask images: var(--icon-<name>). */
const MASKS = ['chevron', 'check']
const EASE = { spring: 'var(--motion-spring)', standard: 'var(--motion-ease)' }

function poseCss(pose) {
  const parts = []
  if (pose.x || pose.y) parts.push(`translate(${pose.x ?? 0}px, ${pose.y ?? 0}px)`)
  if (pose.r) parts.push(`rotate(${pose.r}deg)`)
  const sx = (pose.s ?? 1) * (pose.sx ?? 1)
  const sy = (pose.s ?? 1) * (pose.sy ?? 1)
  if (sx !== 1 || sy !== 1) parts.push(sx === sy ? `scale(${sx})` : `scale(${sx}, ${sy})`)
  return parts.length ? parts.join(' ') : 'none'
}

export function renderIconCss() {
  const lines = [
    '/* Generated by `yarn icons` from src/icon-pack.ts. Do not edit. */',
    ':root {',
    ...MASKS.map(name => `  --icon-${name}: url('data:image/svg+xml,${encodeURIComponent(iconSvg(name))}');`),
    ...Object.entries(REACTIONS).map(([name, r]) => `  --icon-react-${name}: icon-${name} ${r.ms}ms ${EASE[r.ease]}; /* ${r.note} */`),
    '}',
  ]
  for (const [name, r] of Object.entries(REACTIONS)) {
    lines.push(`@keyframes icon-${name} {`)
    for (const [at, pose] of r.frames) lines.push(`  ${at}% {`, `    transform: ${poseCss(pose)};`, '  }')
    lines.push('}')
  }
  return lines.join('\n') + '\n'
}

if (realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('../src/icon-pack.css', import.meta.url), renderIconCss())
  console.log('wrote src/icon-pack.css')
}
