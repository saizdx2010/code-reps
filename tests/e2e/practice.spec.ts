test('desktop desk stays fixed while task and checks scroll', async ({ page }) => {
  for (const height of [900, 600]) {
    await page.setViewportSize({ width: 1280, height })
    await page.goto(route)
    await expect(editor(page)).toBeVisible()
    // Reveal every remaining hint so the brief overflows the roomier compact desk.
    const nextHint = page.getByRole('button', { name: /^Reveal hint/ })
    while (await nextHint.count()) await nextHint.click()
    const task = page.locator('.task-column')
    await task.hover()
    await page.mouse.wheel(0, 1000)
    await expect.poll(() => task.evaluate(node => node.scrollTop)).toBeGreaterThan(0)
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
    await replaceCode(page, solution)
    await page
      .locator('.workspace-toolbar')
      .getByRole('button', { name: /Run checks/ })
      .click()
    await expectChecksFinished(page.getByText('All checks passed', { exact: true }))
    const run = page.locator('.workspace-toolbar').getByRole('button', { name: /Run checks/ })
    const bounds = await run.boundingBox()
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(height)
    expect(await page.locator('.code-column').evaluate(node => node.scrollHeight - node.clientHeight)).toBeLessThanOrEqual(1)
    expect(await page.evaluate(() => document.documentElement.scrollHeight)).toBeLessThanOrEqual(height)
    await page.locator('#check-details').hover()
    await page.mouse.wheel(0, 1000)
    await expect.poll(() => page.locator('#check-details').evaluate(node => node.scrollTop)).toBeGreaterThan(0)
    await page.getByRole('button', { name: /^Checks/ }).click()
    await expect(page.locator('#check-details')).toBeHidden()
    await expect(editor(page)).toBeVisible()
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
  }
})
