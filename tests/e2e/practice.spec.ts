import { expect, test } from '@playwright/test'
import { editor, replaceCode, route, saved, solution } from './helpers'

test('real Monaco editing, keyboard checks, and obsolete feedback', async ({ page }) => {
  await page.goto(route)
  await replaceCode(page, solution)
  await page.keyboard.press('ControlOrMeta+Enter')
  await expect(page.getByText('All checks passed', { exact: true })).toBeVisible()
  await replaceCode(page, 'function mostFrequent(numbers: number[]): number | null { return null }')
  await expect(page.getByText('All checks passed', { exact: true })).toHaveCount(0)
  await page.locator('.workspace-toolbar').getByRole('button', { name: /Run checks/ }).click()
  await expect(page.getByText('1 of 6 checks passed', { exact: true })).toBeVisible()
})

test('reload preserves code and planning drafts', async ({ page }) => {
  await page.goto(route)
  await page.getByLabel('YOUR PLAN', { exact: true }).fill('Count values, then resolve ties with the smaller value.')
  await replaceCode(page, solution)
  await saved(page)
  await page.reload()
  await expect(page.getByLabel('YOUR PLAN', { exact: true })).toHaveValue('Count values, then resolve ties with the smaller value.')
  await expect(editor(page)).toBeVisible()
  await page.locator('.workspace-toolbar').getByRole('button', { name: /Run checks/ }).click()
  await expect(page.getByText('All checks passed', { exact: true })).toBeVisible()
})

test('profile switching keeps drafts separate', async ({ page }) => {
  await page.goto(route)
  await page.getByLabel('YOUR PLAN', { exact: true }).fill('Original profile plan')
  await replaceCode(page, solution)
  await page.getByRole('button', { name: 'Manage profiles' }).click()
  const dialog = page.getByRole('dialog', { name: 'Local profiles' })
  await dialog.getByLabel('Profile name', { exact: true }).fill('Browser test learner')
  await dialog.getByRole('button', { name: 'Create profile', exact: true }).click()
  await expect(dialog.getByRole('status')).toHaveText('Profile created.')
  await dialog.getByRole('button', { name: 'Close', exact: true }).click()
  await page.goto(route)
  await expect(page.getByLabel('YOUR PLAN', { exact: true })).toHaveValue('')
  await expect(editor(page)).toBeVisible()
  await expect(page.locator('.view-lines')).toContainText('Write your solution here')
  await page.getByLabel('YOUR PLAN', { exact: true }).fill('Separate learner plan')
  await page.getByRole('button', { name: 'Manage profiles' }).click()
  await dialog.getByLabel('Switch profile').selectOption({ label: 'My learning' })
  await expect(dialog.getByLabel('Switch profile')).toHaveValue('default')
  await dialog.getByRole('button', { name: 'Close', exact: true }).click()
  await page.goto(route)
  await expect(page.getByLabel('YOUR PLAN', { exact: true })).toHaveValue('Original profile plan')
  await expect(editor(page)).toBeVisible()
  await page.locator('.workspace-toolbar').getByRole('button', { name: /Run checks/ }).click()
  await expect(page.getByText('All checks passed', { exact: true })).toBeVisible()
})

test('narrow workspace preserves planning and supports keyboard exit', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(route)
  await page.getByRole('button', { name: 'Plan', exact: true }).click()
  await page.getByLabel('YOUR PLAN', { exact: true }).fill('A narrow-screen draft')
  await page.getByRole('button', { name: 'Solve', exact: true }).click()
  await replaceCode(page, solution)
  await page.keyboard.press('Tab')
  await expect(editor(page)).not.toBeFocused()
  await page.locator('.workspace-toolbar').getByRole('button', { name: /Run checks/ }).click()
  await expect(page.getByText('All checks passed', { exact: true })).toBeVisible()
  await saved(page)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Plan', exact: true }).click()
  await expect(page.getByLabel('YOUR PLAN', { exact: true })).toHaveValue('A narrow-screen draft')
})

test('first-run choice precedes the recommendation and stays editable', async ({ page }) => {
  await page.goto('/#/home')
  const firstRun = page.locator('.first-run-start')
  await expect(firstRun.getByRole('heading', { name: 'Where are you starting?' })).toBeVisible()
  expect(await page.evaluate(() => Boolean(document.querySelector('.first-run-start')!.compareDocumentPosition(document.querySelector('.continue-panel')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true)
  await firstRun.getByRole('button', { name: /New to coding/ }).click()
  await expect(page.locator('#continue-heading')).toHaveText('Declare a value')
  await expect(firstRun).toHaveCount(0)
  await page.reload()
  await expect(page.locator('#continue-heading')).toHaveText('Declare a value')
  await page.getByText('Change starting point', { exact: true }).click()
  await page.getByRole('button', { name: /Returning to coding/ }).click()
  await expect(page.locator('#continue-heading')).toHaveText('Sum positive numbers')
  await page.locator('.continue-panel').getByRole('button', { name: /Start rep/ }).click()
  await expect(page).toHaveURL(/#\/practice\/sum-positive-numbers$/)
  await page.goBack()
  await expect(page.locator('#continue-heading')).toHaveText('Sum positive numbers')
})

test('failed checks open one case at a time with keyboard access', async ({ page }) => {
  await page.goto(route)
  await page.locator('.workspace-toolbar').getByRole('button', { name: 'Run checks', exact: true }).click()
  await expect(page.getByText('1 of 6 checks passed', { exact: true })).toBeVisible()
  const cases = page.locator('#checks-section .result-list').first().locator('details')
  await expect(cases).toHaveCount(5)
  await expect(page.locator('#checks-section .result-list details[open]')).toHaveCount(1)
  await expect(cases.first()).toHaveAttribute('open', '')
  const second = cases.nth(1).locator('summary')
  await second.focus()
  await second.press('Enter')
  await expect(cases.nth(1)).toHaveAttribute('open', '')
  await expect(cases.first()).not.toHaveAttribute('open', '')
  await expect(page.locator('#checks-section .result-list details[open]')).toHaveCount(1)
  await expect(cases.nth(1)).toContainText('mostFrequent([7])')
  await expect(page.locator('.passed-checks')).not.toHaveAttribute('open', '')
})

test('practice steps preserve work, explain missing requirements, and record completion', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(route)
  const steps = page.getByRole('navigation', { name: 'Practice steps' })
  await steps.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(page.locator('#review-section')).toBeFocused()
  await page.getByRole('button', { name: 'Write your plan', exact: false }).click()
  await expect(page.locator('#plan-section')).toBeFocused()
  await page.getByLabel('YOUR PLAN', { exact: true }).fill('Count occurrences and choose the smaller number when counts tie.')
  await steps.getByRole('button', { name: 'Solve', exact: true }).click()
  await replaceCode(page, solution)
  await page.keyboard.press('ControlOrMeta+Enter')
  await expect(page.getByText('All checks passed', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Explain your solution', exact: false }).click()
  await expect(page.locator('#explain-section')).toBeFocused()
  await page.getByLabel('YOUR EXPLANATION', { exact: true }).fill('I count each value, compare counts, and use the smaller value to break ties. Empty input returns null.')
  await steps.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByLabel('WHAT WAS HARDEST?', { exact: true }).selectOption('edge-cases')
  await page.getByLabel('HOW CONFIDENT DO YOU FEEL?', { exact: true }).selectOption('getting-there')
  await page.getByRole('button', { name: 'Complete rep', exact: false }).click()
  await expect(page.getByText('Completed and saved on this device.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(steps.getByRole('button', { name: 'Review', exact: true })).toHaveAttribute('aria-current', 'step')
  await expect(page.getByLabel('YOUR EXPLANATION', { exact: true })).toHaveValue(/I count each value/)
  await steps.getByRole('button', { name: 'Plan', exact: true }).click()
  await expect(page.getByLabel('YOUR PLAN', { exact: true })).toHaveValue(/Count occurrences/)
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Progress', exact: true }).click()
  // An unhinted solve before its guided journey is not evidence of independence.
  await expect(page.locator('.progress-summary')).toContainText('Independent skills0')
  await expect(page.locator('.progress-summary')).toContainText('Retained skills0')
})

test('lesson section navigation preserves predictions and opens self-review', async ({ page }) => {
  await page.goto('/#/knowledge')
  const sections = page.getByRole('navigation', { name: 'Lesson sections' })
  await sections.getByRole('button', { name: 'Predict', exact: true }).click()
  await expect(page.locator('#lesson-predict')).toBeFocused()
  const prediction = page.locator('fieldset.lesson-question').first()
  await prediction.getByRole('radio', { name: '6', exact: true }).check()
  await prediction.getByRole('button', { name: 'Check prediction', exact: true }).click()
  await expect(prediction).toContainText('Correct prediction.')
  await sections.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(page.locator('.lesson-review-details')).toHaveAttribute('open', '')
  await expect(page.locator('#lesson-review')).toBeFocused()
  await page.getByLabel('Evidence and what to improve', { exact: true }).fill('I traced the return value; I still need an independent coding attempt.')
  await sections.getByRole('button', { name: 'Read', exact: true }).click()
  await sections.getByRole('button', { name: 'Predict', exact: true }).click()
  await expect(prediction.getByRole('radio', { name: '6', exact: true })).toBeChecked()
  await page.reload()
  await expect(prediction).toContainText('Correct prediction.')
  await sections.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(page.getByLabel('Evidence and what to improve', { exact: true })).toHaveValue(/I traced the return value/)
})

